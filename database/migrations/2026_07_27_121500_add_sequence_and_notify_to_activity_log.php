        DB::statement('create index activity_log_seq_idx on activity_log (seq)');

        // The payload is the sequence only. Postgres caps a notification at
        // 8000 bytes, and an entry with a large jsonb payload would exceed
        // it — the listener re-reads the row by seq instead.
