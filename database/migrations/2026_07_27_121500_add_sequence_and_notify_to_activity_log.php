        // An identity column rather than a standalone sequence: the sequence
        // behind it belongs to the column and is dropped with the table.
        // A free-standing `create sequence` survives `migrate:fresh` — that
        // drops tables, not sequences — and the next run dies on a name that
        // is already taken.
