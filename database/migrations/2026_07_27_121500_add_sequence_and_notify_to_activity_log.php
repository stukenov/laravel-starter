/**
 * RULE(sse): a resumable stream needs a monotonic cursor.
 *
 * The uuid key sorts by creation time, but a browser reconnecting with
 * Last-Event-ID needs to ask for "everything after N" — a comparison the
 * client can hold as a number and the server can index. So the log carries
 * a bigint sequence alongside its uuid.
 *
 * The trigger is what makes the stream live: it fires pg_notify on insert,
 * and the SSE handler sleeps on the socket until it arrives instead of
 * polling the table. See AGENTS.md.
 */
return new class extends Migration
{
